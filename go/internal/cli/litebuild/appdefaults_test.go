// appModel is a small master configuration in the shape of the wendy-lite
// one: a board sets the chip and the flash size, and the native app type
// selects a partition table from the repository.
const appModel = `
attributes:
  board: {type: string, enum: [c61_board, s3_board]}
  chip: {type: string, enum: [esp32c61, esp32s3]}
  idf_version: {type: string, enum: ["6.0.3", "6.1"]}
  idf_preview: {type: boolean}
  flash_size: {type: size}
  app_type: {type: string, enum: [native, wasm]}
  cloud_tunnel: {type: boolean}
rules:
  - if: board == "c61_board"
    set: {chip: esp32c61, flash_size: 4MiB, app_type: native}
  - if: board == "s3_board"
    set: {chip: esp32s3, flash_size: 8MiB}
  - if: chip == "esp32s3"
    set: {idf_version: "6.1", idf_preview: true}
  - else:
    set: {idf_version: "6.0.3", idf_preview: false}
  - if: app_type == "wasm" && cloud_tunnel
    valid: false
  - if: flash_size == 4MiB
    sdkconfig: |
      CONFIG_ESPTOOLPY_FLASHSIZE_4MB=y
  - if: flash_size == 4MiB && app_type == "native"
    sdkconfig: |
      CONFIG_PARTITION_TABLE_CUSTOM=y
      CONFIG_PARTITION_TABLE_CUSTOM_FILENAME="partitions.ota.csv"
  - if: cloud_tunnel
    sdkconfig: |
      CONFIG_WENDY_CLOUD_TUNNEL=y
  - else:
    sdkconfig: |
      CONFIG_WENDY_CLOUD_TUNNEL=n
`

func loadAppModel(t *testing.T) *Model {
	t.Helper()
	m, err := Load([]byte(appModel), "wendy-lite abc1234:master_config.yaml")
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func TestParseBuildProfile(t *testing.T) {
	m := loadAppModel(t)
	inputs, err := ParseBuildProfile(m, "board: c61_board\ncloud_tunnel: true\nflash_size: '4MiB'\napp_type:")
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]any{"board": "c61_board", "cloud_tunnel": true, "flash_size": int64(4 << 20)}
	if len(inputs) != len(want) {
		t.Fatalf("inputs = %v, want %v", inputs, want)
	}
	for name, v := range want {
		if inputs[name] != v {
			t.Errorf("%s = %#v, want %#v", name, inputs[name], v)
		}
	}
	// BuildProfile writes what ParseBuildProfile reads.
	back, err := ParseBuildProfile(m, m.BuildProfile(inputs))
	if err != nil {
		t.Fatal(err)
	}
	if m.BuildProfile(back) != m.BuildProfile(inputs) {
		t.Errorf("round trip: %q, want %q", m.BuildProfile(back), m.BuildProfile(inputs))
	}

	if inputs, err := ParseBuildProfile(m, ""); err != nil || len(inputs) != 0 {
		t.Errorf("empty profile = %v, %v; want no values", inputs, err)
	}
	for text, wantErr := range map[string]string{
		"color: red":               `unknown attribute "color"`,
		"board: other":             "is not one of",
		"cloud_tunnel: maybe":      "is not a boolean",
		"board: [c61_board]":       "must be a single value",
		"- board":                  "expected name: value lines",
		"board: a\nboard: b":       "given twice",
		"board: c61_board\n  x: y": "build profile",
	} {
		if _, err := ParseBuildProfile(m, text); err == nil || !strings.Contains(err.Error(), wantErr) {
			t.Errorf("ParseBuildProfile(%q) error = %v, want %q", text, err, wantErr)
		}
	}
}

func TestAppDefaultsText(t *testing.T) {
	m := loadAppModel(t)
	text, err := AppDefaultsText(m, "abc1234def", "board: c61_board\ncloud_tunnel: true", "esp32c61")
	if err != nil {
		t.Fatal(err)
	}
	want := `# Generated by the Wendy CLI configurator from wendy-lite abc1234:master_config.yaml. Do not edit.
# Command line: board=c61_board cloud_tunnel=true
# The partition table lines (CONFIG_PARTITION_TABLE_*) of the firmware are left out.
CONFIG_WENDY_BUILD_PROFILE="board: c61_board\\ncloud_tunnel: true"
CONFIG_WENDY_VERSION="abc1234def"
CONFIG_ESPTOOLPY_FLASHSIZE_4MB=y
CONFIG_WENDY_CLOUD_TUNNEL=y
`
	if text != want {
		t.Errorf("AppDefaultsText =\n%s\nwant\n%s", text, want)
	}

	// No partition table line to leave out: no comment about it.
	text, err = AppDefaultsText(m, "v1", "board: s3_board\napp_type: native\ncloud_tunnel: false", "esp32s3")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(text, "partition") {
		t.Errorf("AppDefaultsText without partition lines mentions them:\n%s", text)
	}

	for _, tc := range []struct {
		name, profile, target, wantErr string
	}{
		{"chip mismatch", "board: c61_board\ncloud_tunnel: true", "esp32s3", "the build profile is for the esp32c61, but the device is a esp32s3"},
		{"not allowed", "board: s3_board\napp_type: wasm\ncloud_tunnel: true", "esp32s3", "not allowed"},
		{"missing value", "board: c61_board", "esp32c61", "missing value(s): cloud_tunnel"},
		{"missing chip", "cloud_tunnel: false", "esp32c61", "missing value(s): chip"},
		{"conflict", "board: c61_board\nchip: esp32s3\ncloud_tunnel: true", "esp32c61", "conflict on chip"},
		{"bad profile", "board: nope", "esp32c61", "is not one of"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := AppDefaultsText(m, "v1", tc.profile, tc.target)
			if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Errorf("error = %v, want %q", err, tc.wantErr)
			}
		})
	}
}

func TestCheckAppDefaults(t *testing.T) {
	m := loadAppModel(t)
	const profile = "board: c61_board\ncloud_tunnel: true"
	text, err := AppDefaultsText(m, "abc1234def", profile, "esp32c61")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()

	status, err := CheckAppDefaults(dir, "abc1234def", profile)
	if err != nil || status.State != AppDefaultsMissing {
		t.Fatalf("no file: %+v, %v; want missing", status, err)
	}

	if err := os.WriteFile(filepath.Join(dir, AppDefaultsFile), []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		name, version, profile string
		want                   AppDefaultsState
	}{
		{"same", "abc1234def", profile, AppDefaultsOK},
		{"same profile, other quoting and order", "abc1234def", "cloud_tunnel: true\nboard: 'c61_board'", AppDefaultsOK},
		{"other version", "fff0000", profile, AppDefaultsOutdated},
		{"other profile", "abc1234def", "board: c61_board\ncloud_tunnel: false", AppDefaultsOutdated},
		{"profile with one more value", "abc1234def", profile + "\nflash_size: 4MiB", AppDefaultsOutdated},
		{"device profile not YAML", "abc1234def", "board: [", AppDefaultsOutdated},
	} {
		t.Run(tc.name, func(t *testing.T) {
			status, err := CheckAppDefaults(dir, tc.version, tc.profile)
			if err != nil {
				t.Fatal(err)
			}
			if status.State != tc.want {
				t.Errorf("state = %v, want %v", status.State, tc.want)
			}
			if status.Version != "abc1234def" || status.Profile != profile {
				t.Errorf("file values = %q, %q; want %q, %q", status.Version, status.Profile, "abc1234def", profile)
			}
		})
	}

	// A file without the two lines, for example written by hand.
	if err := os.WriteFile(filepath.Join(dir, AppDefaultsFile), []byte("CONFIG_X=y\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	status, err = CheckAppDefaults(dir, "abc1234def", profile)
	if err != nil || status.State != AppDefaultsOutdated || status.Version != "" || status.Profile != "" {
		t.Errorf("file without the lines: %+v, %v; want outdated with no values", status, err)
	}
}

func TestKconfigStrings(t *testing.T) {
	got := kconfigStrings("# comment\nCONFIG_A=\"x \\\"q\\\" \\\\ y\"\r\nCONFIG_B=y\nCONFIG_C=\"\"\nOTHER=\"z\"\n")
	if got["CONFIG_A"] != `x "q" \ y` {
		t.Errorf("CONFIG_A = %q", got["CONFIG_A"])
	}
	if v, ok := got["CONFIG_C"]; !ok || v != "" {
		t.Errorf("CONFIG_C = %q, %v; want empty", v, ok)
	}
	if _, ok := got["CONFIG_B"]; ok {
		t.Error("CONFIG_B is not a string")
	}
	if _, ok := got["OTHER"]; ok {
		t.Error("OTHER is not a CONFIG_ option")
	}
	if kconfigString(`a"b\c`) != `"a\"b\\c"` {
		t.Errorf("kconfigString = %s", kconfigString(`a"b\c`))
	}
}

func TestSolveProfile(t *testing.T) {
	m := loadAppModel(t)
	ps, err := SolveProfile(m, "board: c61_board\ncloud_tunnel: true", "esp32c61")
	if err != nil {
		t.Fatal(err)
	}
	if ps.IDFVersion != "6.0.3" || ps.IDFPreview || ps.Inputs["board"] != "c61_board" || ps.Solution.Values["chip"] != "esp32c61" {
		t.Errorf("SolveProfile = %+v", ps)
	}
	ps, err = SolveProfile(m, "board: s3_board\napp_type: native\ncloud_tunnel: false", "esp32s3")
	if err != nil {
		t.Fatal(err)
	}
	if ps.IDFVersion != "6.1" || !ps.IDFPreview {
		t.Errorf("s3: IDFVersion, IDFPreview = %q, %v; want 6.1, true", ps.IDFVersion, ps.IDFPreview)
	}

	// A master configuration without the ESP-IDF attributes cannot build.
	noIDF, err := Load([]byte("attributes:\n  chip: {type: string}\nrules:\n  - if: chip == \"esp32c61\"\n    sdkconfig: CONFIG_X=y\n"), "no-idf")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := SolveProfile(noIDF, "chip: esp32c61", "esp32c61"); err == nil || !strings.Contains(err.Error(), "does not declare it") {
		t.Errorf("without the ESP-IDF attributes: %v, want an error naming the missing one", err)
	}
}
