package litebuild

import (
	"fmt"
	"path/filepath"
	"strings"
)

// DefaultRef is the wendy-lite tag or branch that the CLI builds without
// --nightly or --version. The Python parity test (TestPythonParity) checks
// the master configuration of this ref.
//
// TEMPORARY: the configurator is on this branch only.
const DefaultRef = "gab/configurator"

// MasterConfPath returns the master configuration of the wendy-lite sources
// in root.
func MasterConfPath(root string) string {
	return filepath.Join(root, "master_config.yaml")
}

// Header returns the comment lines at the top of the sdkconfig text: the
// master configuration and the NAME=VALUE arguments that give the same
// result with tools/configurator/solve.py.
func (m *Model) Header(inputs map[string]any) []string {
	header := []string{fmt.Sprintf("# Generated by the Wendy CLI configurator from %s. Do not edit.", m.Path)}
	if args := m.Assignments(inputs); len(args) > 0 {
		header = append(header, "# Command line: "+strings.Join(args, " "))
	}
	return header
}
