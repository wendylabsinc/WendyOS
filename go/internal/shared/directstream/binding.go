package directstream

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/binary"
	"errors"
)

const AttachmentExporterLabel = "EXPORTER-wendy-direct-attachment/1"
const attachmentContextDomain = "wendy/direct/attachment-context/1\x00"
const attachmentProofDomain = "wendy/direct/attachment-proof/1\x00"

// Attachment binds a frozen reconciliation snapshot to one logical generation.
// IdentityDigest covers the ordered, authenticated endpoint principals, process
// instances and security epochs. SnapshotDigest covers both frozen flow views.
// Neither digest may be accepted merely because it was supplied by the peer.
// Nonces are independently generated by each endpoint for this transaction.
// Mode is 0 for direct BLE, 1 for promotion; promotion cannot be undone until
// bilateral quiescence. A session actor must enforce that state transition.
type Attachment struct {
	// AttachmentID is a nonzero, never-reused alias on this TLS connection.
	// Every DATA/control frame carries it to fence retired logical sessions,
	// including after bilateral quiescence on a still-live carrier.
	AttachmentID                       uint32
	SessionID                          [32]byte
	Generation                         uint64
	Mode                               byte
	CoordinatorNonce, ParticipantNonce [16]byte
	IdentityDigest, SnapshotDigest     [32]byte
}

func (a Attachment) Context() ([32]byte, error) {
	if a.Generation == 0 || a.Mode > 1 || a.AttachmentID == 0 {
		return [32]byte{}, errors.New("invalid attachment generation or mode")
	}
	h := sha256.New()
	h.Write([]byte(attachmentContextDomain))
	h.Write(a.SessionID[:])
	var generation [8]byte
	binary.BigEndian.PutUint64(generation[:], a.Generation)
	h.Write(generation[:])
	h.Write([]byte{a.Mode})
	var alias [4]byte
	binary.BigEndian.PutUint32(alias[:], a.AttachmentID)
	h.Write(alias[:])
	h.Write(a.CoordinatorNonce[:])
	h.Write(a.ParticipantNonce[:])
	h.Write(a.IdentityDigest[:])
	h.Write(a.SnapshotDigest[:])
	var out [32]byte
	copy(out[:], h.Sum(nil))
	return out, nil
}

// AttachmentProof requires a fresh TLS exporter from the authenticated candidate
// connection, using AttachmentExporterLabel and Context() as its context. The
// capability is a random session secret, never a TLS ticket or exporter. Role 0
// is the logical coordinator, 1 the participant (not the physical TLS role).
func AttachmentProof(capability, exporter, context [32]byte, role byte) ([32]byte, error) {
	if role > 1 {
		return [32]byte{}, errors.New("invalid attachment proof role")
	}
	h := hmac.New(sha256.New, capability[:])
	h.Write([]byte(attachmentProofDomain))
	h.Write([]byte{role})
	h.Write(exporter[:])
	h.Write(context[:])
	var out [32]byte
	copy(out[:], h.Sum(nil))
	return out, nil
}

func VerifyAttachmentProof(capability, exporter, context [32]byte, role byte, proof []byte) bool {
	expected, err := AttachmentProof(capability, exporter, context, role)
	return err == nil && hmac.Equal(expected[:], proof)
}
