    def test_source_identity_includes_dirty_deletions(self):
        path = self.repo / "deleted.go"
        path.write_text("package fixture\n")
        subprocess.run(["git", "add", str(path)], cwd=self.repo, check=True)
        before = coverage.source_id(self.repo)
        path.unlink()
