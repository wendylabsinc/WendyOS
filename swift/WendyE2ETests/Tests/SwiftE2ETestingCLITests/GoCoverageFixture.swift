import Foundation
import Testing

@testable import SwiftE2ETestingCLI

final class GoCoverageFixture {
    let repo: URL
    var run: URL { repo.appendingPathComponent("run") }
    var source: [String: Any] {
        get throws { try CoverageIO.read(run.appendingPathComponent("coverage/source.json")) }
    }
    var cli: URL { run.appendingPathComponent("coverage/bin/wendy") }
    var agent: URL { run.appendingPathComponent("coverage/bin/wendy-agent") }
    let product = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
        .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        .deletingLastPathComponent()

    init(build: Bool = true, managed: Bool = false) throws {
        repo = try CoverageIO.temporaryDirectory()
        let module = try String(
            contentsOf: product.appendingPathComponent("go.mod"),
            encoding: .utf8
        )
        let toolchain = try #require(CoverageIO.lines(module).first { $0.hasPrefix("go ") })
        try write("go.mod", "module example.test/coverage\n\n" + toolchain + "\n")
        try write(".gitignore", "/run*/\n/binary-*\n/fake-bin/\n")
        try write("go/internal/sample/branch.go", Self.branch)
        try write(
            "go/internal/sample/generated.go",
            "// Code generated by fixture. DO NOT EDIT.\npackage sample\nfunc Generated() int { return 99 }\n"
        )
        try write(
            "go/cmd/wendy/main.go",
            """
            package main
            import ("fmt"; "os"; "time"; "example.test/coverage/go/internal/sample")
            func main() {
                fmt.Println(sample.Branch(os.Args[1]))
                if os.Args[1] == "fail" { os.Exit(7) }
                if os.Args[1] == "hang" { time.Sleep(time.Hour) }
            }
            """
        )
        try write(
            "go/cmd/wendy-agent/main.go",
            """
            package main
            import ("bufio"; "fmt"; "os"; "example.test/coverage/go/internal/sample")
            func main() {
                fmt.Println("ready")
                scanner := bufio.NewScanner(os.Stdin)
                for scanner.Scan() { fmt.Println(sample.Branch(scanner.Text())) }
            }
            """
        )
        for role in ["wendy", "wendy-agent"] {
            let hook = product.appendingPathComponent("go/cmd/\(role)/coverage_e2e.go")
            try write("go/cmd/\(role)/coverage_e2e.go", String(contentsOf: hook, encoding: .utf8))
        }
        _ = try git(["init", "-q"])
        _ = try commit()
        if build { try buildBinaries(managed: managed) }
    }
    deinit { try? FileManager.default.removeItem(at: repo) }
    static let branch = """
        package sample
        func Branch(value string) int {
            if value == "left" { return 1 }
            return 2
        }
        """ + "\n"
    func write(_ path: String, _ text: String) throws {
        let destination = repo.appendingPathComponent(path)
        try FileManager.default.createDirectory(
            at: destination.deletingLastPathComponent(),
            withIntermediateDirectories: true
        )
        try text.write(to: destination, atomically: true, encoding: .utf8)
    }
    func git(_ args: [String]) throws -> String {
        try CoverageIO.command(["git"] + args, cwd: repo).trimmingCharacters(
            in: .whitespacesAndNewlines
        )
    }
    @discardableResult func commit() throws -> String {
        _ = try git(["add", "."])
        _ = try git([
            "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "-c",
            "commit.gpgsign=false", "commit", "-qm", "fixture", "--allow-empty",
        ])
        return try git(["rev-parse", "HEAD"])
    }
    func buildBinaries(managed: Bool = false) throws {
        try GoCoverage(repo: repo, run: run).prepare(managed: managed)
        try FileManager.default.createDirectory(
            at: cli.deletingLastPathComponent(),
            withIntermediateDirectories: true
        )
        for role in managed ? ["wendy", "wendy-agent"] : ["wendy"] {
            _ = try CoverageIO.command(
                [
                    "go", "build", "-cover", "-covermode=atomic", "-tags=e2e_coverage", "-o",
                    run.appendingPathComponent("coverage/bin/" + role).path, "./go/cmd/" + role,
                ],
                cwd: repo
            )
        }
    }
    func native(_ path: String) throws -> URL {
        let url = run.appendingPathComponent(path)
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }
    @discardableResult func invoke(_ directory: URL, _ argument: String) throws -> Int32 {
        var env = ProcessInfo.processInfo.environment
        env["GOCOVERDIR"] = directory.path
        return try CoverageIO.execute([cli.path, argument], environment: env).status
    }
    func records(_ records: [[String: Any]]) throws {
        try CoverageIO.write(records, to: run.appendingPathComponent("coverage/tests.json"))
    }
    func record(_ name: String, directory: String) throws -> [String: Any] {
        [
            "test": name, "status": "collected", "sourceID": try source["sourceID"]!,
            "directory": directory,
            "cliInvocations": try CoverageIO.files(
                run.appendingPathComponent(directory + "/coverage/go"),
                prefix: "invocation."
            ).count,
        ]
    }
    func attempt(exit: Int = 0) throws {
        try CoverageIO.write(
            ["git": ["commit": try git(["rev-parse", "HEAD"])], "exitStatus": exit],
            to: run.appendingPathComponent("attempt.json")
        )
    }
    static func json(_ path: URL) throws -> [String: Any] { try CoverageIO.read(path) }
    static func line(_ handle: FileHandle) throws -> String {
        var data = Data()
        while let byte = try handle.read(upToCount: 1), !byte.isEmpty {
            if byte.first == 10 { break }
            data.append(byte)
        }
        return String(decoding: data, as: UTF8.self)
    }
}
